#!/usr/bin/env python3
"""Render the skills index into the global AGENTS.md from every SKILL.md's frontmatter.

The SKILL.md `description` is the single source of truth: Claude Code and opencode both
read it to decide when to load a skill, and this index is generated from it, so the
list in AGENTS.md can never drift from the skills on disk.

  index.py            # print the generated blocks
  index.py --write    # replace both blocks between their markers in workstation/config/AGENTS.md
  index.py --write-repo  # the repo-skills and chipi/infra blocks (keeps the committed third-party list)
  index.py --check    # exit 1 if the repo-skills block is stale (CI runs this); also
                      #   warns about repo skills not installed on this machine
  index.py --check-install  # exit 1 if a repo skill is not linked into ~/.claude/skills,
                            #   or a chipi/infra skill is not linked into the infra checkout

Three blocks: the operator's skills (this directory — checked in CI); the product skills in
the private chipi/infra checkout's skills/ (written by --write on a machine that has the
checkout, never checked in CI, which cannot read it); and third-party skills installed on
THIS machine (~/.claude/skills entries that link into neither — written by --write, never
checked). The infra checkout is $INFRA_CHECKOUT, else the first of ~/projects/infra and
/work/infra/main that has skills/ (install.sh uses the same rule).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AGENTS = os.path.join(HERE, "..", "..", "config", "AGENTS.md")
BEGIN = "<!-- skills-index:begin (generated by workstation/claude/skills/index.py — do not edit by hand) -->"
END = "<!-- skills-index:end -->"
TP_BEGIN = "<!-- skills-thirdparty:begin (generated by workstation/claude/skills/index.py --write from this machine; not checked in CI) -->"
TP_END = "<!-- skills-thirdparty:end -->"
INFRA_BEGIN = "<!-- skills-infra:begin (generated by workstation/claude/skills/index.py --write from a machine with the chipi/infra checkout; not checked in CI) -->"
INFRA_END = "<!-- skills-infra:end -->"
CLAUDE_SKILLS = os.path.expanduser("~/.claude/skills")


def infra_skills_dir():
    env = os.environ.get("INFRA_CHECKOUT")
    for c in ([env] if env else ["~/projects/infra", "/work/infra/main"]):
        d = os.path.join(os.path.expanduser(c), "skills")
        if os.path.isdir(d):
            return d
    return None


def frontmatter(path):
    text = open(path).read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    return fm


def split_description(desc):
    """(what, when): the 'Use when/for/to …' sentence is the trigger; the rest is what it does."""
    sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z])", desc)
    when = [s for s in sentences if re.match(r"(Use|Run|Invoke|Trigger)\b", s)]
    what = [s for s in sentences if s not in when]
    return " ".join(what).strip(), " ".join(when).strip()


def what_when(fm):
    """`when_to_use` (Claude Code skill frontmatter, matched together with the
    description) is the trigger when present; otherwise the description's own
    'Use when …' sentence."""
    if fm.get("when_to_use"):
        return fm["description"].strip(), fm["when_to_use"].strip()
    return split_description(fm["description"])


def _row(name, p):
    fm = frontmatter(p)
    if not fm or "description" not in fm:
        return None
    what, when = what_when(fm)
    cell = lambda s: s.replace("|", "\\|")
    return f"| `{fm.get('name', name)}` | {cell(when) or '—'} | {cell(what)} |"


def render_thirdparty():
    rows = []
    if os.path.isdir(CLAUDE_SKILLS):
        for name in sorted(os.listdir(CLAUDE_SKILLS)):
            d = os.path.join(CLAUDE_SKILLS, name)
            if os.path.realpath(d).startswith(os.path.realpath(HERE) + os.sep):
                continue                      # an operator skill, already in the first block
            infra = infra_skills_dir()
            if infra and os.path.realpath(d).startswith(os.path.realpath(infra) + os.sep):
                continue                      # a chipi/infra skill, in the infra block
            p = os.path.join(d, "SKILL.md")
            r = _row(name, p) if os.path.isfile(p) else None
            if r:
                rows.append(r)
    head = ["| Skill | Load it when | What it does |", "|---|---|---|"]
    return "\n".join([TP_BEGIN, ""] + head + rows + ["", TP_END])


def render_infra():
    """The chipi/infra block, or None when this machine has no infra checkout."""
    d = infra_skills_dir()
    if not d:
        return None
    rows = [r for r in (_row(n, os.path.join(d, n, "SKILL.md")) for n in sorted(os.listdir(d))
                        if os.path.isfile(os.path.join(d, n, "SKILL.md"))) if r]
    head = ["| Skill | Load it when | What it does |", "|---|---|---|"]
    return "\n".join([INFRA_BEGIN, ""] + head + rows + ["", INFRA_END])


def render():
    rows = []
    for name in sorted(os.listdir(HERE)):
        p = os.path.join(HERE, name, "SKILL.md")
        if not os.path.isfile(p):
            continue
        fm = frontmatter(p)
        if not fm or "description" not in fm:
            sys.exit(f"{p}: missing frontmatter description — every skill needs one (it is the trigger)")
        what, when = what_when(fm)
        cell = lambda s: s.replace("|", "\\|")
        rows.append(f"| `{fm.get('name', name)}` | {cell(when) or '—'} | {cell(what)} |")
    head = ["| Skill | Load it when | What it does |", "|---|---|---|"]
    return "\n".join([BEGIN, ""] + head + rows + ["", END])


def install_drift():
    """Repo skills an agent on THIS machine can't load: not in ~/.claude/skills, or a
    link that no longer resolves. None when ~/.claude/skills doesn't exist (CI)."""
    if not os.path.isdir(CLAUDE_SKILLS):
        return None
    out = []
    for name in sorted(os.listdir(HERE)):
        if not os.path.isfile(os.path.join(HERE, name, "SKILL.md")):
            continue
        d = os.path.join(CLAUDE_SKILLS, name)
        if not os.path.isfile(os.path.join(d, "SKILL.md")):
            out.append(f"{name} ({'dangling link' if os.path.islink(d) else 'not linked'})")
    infra = infra_skills_dir()
    if infra:
        for name in sorted(os.listdir(infra)):
            if not os.path.isfile(os.path.join(infra, name, "SKILL.md")):
                continue
            d = os.path.join(CLAUDE_SKILLS, name)
            if not os.path.realpath(d).startswith(os.path.realpath(infra) + os.sep):
                out.append(f"{name} (not linked to the chipi/infra checkout)")
    return out


def report_drift(drift):
    print(f"NOT INSTALLED on this machine ({len(drift)}): " + ", ".join(drift))
    print("  fix: bash workstation/install.sh --dry-run, then without --dry-run")


def main():
    block = render()
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    if mode == "--check-install":
        drift = install_drift()
        if drift is None:
            print(f"no {CLAUDE_SKILLS} on this machine; nothing to check")
            return 0
        if drift:
            report_drift(drift)
            return 1
        print("all repo skills installed")
        return 0
    if not mode:
        print(block + "\n\n" + (render_infra() or "(no chipi/infra checkout)") + "\n\n" + render_thirdparty())
        return 0
    text = open(AGENTS).read()
    if BEGIN not in text or END not in text:
        sys.exit(f"markers not found in {AGENTS}; add them where the index should go")
    current = text[text.index(BEGIN):text.index(END) + len(END)]
    if mode == "--check":
        if current != block:
            print("skills index in AGENTS.md is STALE — run: python3 workstation/claude/skills/index.py --write")
            return 1
        print("skills index up to date")
        drift = install_drift()
        if drift:                        # a warning: CI has no ~/.claude/skills
            report_drift(drift)
        return 0
    if mode in ("--write", "--write-repo"):
        text = text.replace(current, block)
        tp = render_thirdparty()
        # --write-repo leaves the machine-specific third-party block as committed
        # (a write from the Linux workstation would replace the laptop's list).
        if mode == "--write" and TP_BEGIN in text and TP_END in text:
            old = text[text.index(TP_BEGIN):text.index(TP_END) + len(TP_END)]
            text = text.replace(old, tp)
        inf = render_infra()
        if inf and INFRA_BEGIN in text and INFRA_END in text:
            old = text[text.index(INFRA_BEGIN):text.index(INFRA_END) + len(INFRA_END)]
            text = text.replace(old, inf)
        open(AGENTS, "w").write(text)
        print(f"wrote skills index ({block.count(chr(10) + '| `')} repo skills, "
              f"{(inf or '').count(chr(10) + '| `') if inf else 'no checkout:'} chipi/infra, "
              f"{tp.count(chr(10) + '| `')} third-party) into {os.path.relpath(AGENTS)}")
        return 0
    sys.exit("usage: index.py [--write | --write-repo | --check | --check-install]")


if __name__ == "__main__":
    sys.exit(main())
